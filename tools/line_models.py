"""Writes web/studio/linemodels.js: the CP and FD models of the typical lines and cables that the tutorials use (4.4, 4.5), computed by
pcl/lineconst.py from the same data as Parts.TLM_TYPICAL. The tutorials attach them to their 'TLM' parts with the key
of their own parameters (Parts.tlmKey), so they run without the server (Node, tests). tests/test_lines.py checks that
the file matches a fresh computation.

    python tools/line_models.py           # write the file
    python tools/line_models.py --check   # exit 1 if the file is out of date
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from pcl import lineconst as lc  # noqa: E402

OUT = ROOT / 'web' / 'studio' / 'linemodels.js'
# (key, typical line, length in km, model, CP frequency in Hz)
CASES = [('400kV|100|cp|50', '400kV', 100, 'cp', 50.0), ('400kV|100|cp|5000', '400kV', 100, 'cp', 5000.0),
         ('400kV|100|fd', '400kV', 100, 'fd', None),
         # 4.5: the submarine cable of the tutorial 'cable_fd'
         ('220kV-sea|30|cp|50', '220kV-sea', 30, 'cp', 50.0), ('220kV-sea|30|fd', '220kV-sea', 30, 'fd', None)]


def _round(x):
    if isinstance(x, float):
        return float(f'{x:.12g}')
    if isinstance(x, list):
        return [_round(v) for v in x]
    if isinstance(x, dict):
        return {k: _round(v) for k, v in x.items()}
    return x


def models():
    out = {}
    for key, line, L, kind, f in CASES:
        d = lc.typical(line)
        m = lc.cp_model(d, f, L) if kind == 'cp' else lc.fd_model(d, L)
        out[key] = _round(json.loads(json.dumps(m)))
    return out


def text(ms):
    body = json.dumps(ms, ensure_ascii=False, separators=(',', ':'))
    return ("'use strict';\n// Generated by tools/line_models.py from pcl/lineconst.py (4.4, 4.5): the CP and FD models of the typical lines and cables used\n"
            "// by the tutorials, keyed 'line|length|model|f'. Do not edit; run the tool again after a change of the routine.\n"
            "(function(root){const M=" + body + ";root.LineModels=M;if(typeof module!=='undefined')module.exports=M;})"
            "(typeof window!=='undefined'?window:globalThis);\n")


def stored():
    t = OUT.read_text(encoding='utf-8')
    return json.loads(t[t.index('const M=') + 8:t.index(';root.LineModels')])


def check():
    """Largest relative difference between the stored and a fresh model, as the admittance of the line seen from its
    ends over 1 Hz … 1 MHz (the fit itself may differ in its last digits between NumPy builds)."""
    import numpy as np
    old, new = stored(), models()
    if set(old) != set(new):
        return float('inf')
    e = 0.0
    for k in new:
        for f in np.logspace(0, 6, 25):
            s = 2j * np.pi * f
            a, b = lc._line_y(None, old[k], s, {}), lc._line_y(None, new[k], s, {})
            e = max(e, float(np.abs(a - b).max() / np.abs(b).max()))
    return e


def main():
    t = text(models())
    if '--check' in sys.argv:
        err = check()
        print('linemodels.js', f'matches a fresh computation (largest difference {err:.1e})' if err < 1e-3
              else f'OUT OF DATE, difference {err:.1e} (python tools/line_models.py)')
        return 0 if err < 1e-3 else 1
    OUT.write_text(t, encoding='utf-8')
    print('wrote', OUT.relative_to(ROOT), len(t), 'bytes')
    return 0


if __name__ == '__main__':
    sys.exit(main())
